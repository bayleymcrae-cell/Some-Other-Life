export const QUOTE_TIMEZONE = "Australia/Brisbane";
const FIRST_DAY = Date.UTC(2026, 10, 20) / 86400000;
const dateFormatter = new Intl.DateTimeFormat("en-AU", {
  timeZone: QUOTE_TIMEZONE, year: "numeric", month: "2-digit", day: "2-digit",
});
const labelFormatter = new Intl.DateTimeFormat("en-AU", {
  timeZone: QUOTE_TIMEZONE, weekday: "long", day: "numeric", month: "long",
});
const clockFormatter = new Intl.DateTimeFormat("en-AU", {
  timeZone: QUOTE_TIMEZONE, hour: "numeric", minute: "2-digit", hour12: true,
});

export function getDailyInspiration(now = new Date()) {
  const parts = Object.fromEntries(dateFormatter.formatToParts(now)
    .filter(part => part.type !== "literal").map(part => [part.type, part.value]));
  const serial = Date.UTC(Number(parts.year), Number(parts.month) - 1, Number(parts.day)) / 86400000;
  const index = ((serial - FIRST_DAY) % dailyQuotes.length + dailyQuotes.length) % dailyQuotes.length;
  return {
    quote: dailyQuotes[index],
    dateKey: parts.year + "-" + parts.month + "-" + parts.day,
    dateLabel: labelFormatter.format(now),
    timeLabel: clockFormatter.format(now).toUpperCase(),
  };
}

